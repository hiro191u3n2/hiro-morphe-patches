def compile_unit(source, fast=False):
    text = source
    defines = (
        "#version 310 es\n"
        "#define GX_LOCAL_SIZE 64\n"
        "#define GX_STRONG_MODE 3\n"
        "#define GX_TILE_WIDTH 8\n"
        "#define GX_IEEE_DIV73 1\n"
        "#define GX_POW2_EXACT78 1\n"
        f"#define GX_DIV_FAST19115 {int(fast)}\n"
    )
    assert text.count("#version 310 es") == 1
    return text.replace("#version 310 es\n", defines, 1)


def load_transport(source):
    path = source / "tests1964/strong_tiles1964.py"
    spec = importlib.util.spec_from_file_location("strong_tiles1964_for_quotient", path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def representative_cases(transport, count):
    # Original test fixture covers odd boundaries, absent/zero policies,
    # alpha holes, nonzero origins, bounded evidence and maps, confidence.
    rng = np.random.default_rng(19643233)
    selected = []
    for case in range(30, 30 + 40 * max(1, (count + 9) // 10)):
        mode, u, arrays, first = transport.case_data(rng, case)
        if mode == 3:
            selected.append((f"original-{case}", u, arrays, first))
            if len(selected) == count:
                break
    assert len(selected) == count
    for label, u, arrays, first in selected[::5]:
        disabled = u.copy()
        disabled[12] = 0
        selected.append((label + "-no-confidence", disabled, arrays, first))
    assert {int(u[12]) for _, u, _, _ in selected} == {0, 1}, "confidence cases missing"
    return selected


def wide_case(width, full_height, confidence, core_rows=16):
    """Actual camera width and real full-height coordinates, bounded bands."""
    height = core_rows + 8
    rng = np.random.default_rng(width * 91 + full_height + confidence)
    u = np.zeros(32, np.int32)
    u[:13] = [width, height, 4, 4 + core_rows, 4, 4 + core_rows,
              128, full_height, 4, 1, 3, 1, confidence]
    rgb = rng.integers(20, 230, (height, width, 3), dtype=np.uint32)
    rgb[::4] = np.clip(rgb[::4] + 9, 0, 255)
    image = (np.uint32(0xff000000) | rgb[:, :, 0] << 16 | rgb[:, :, 1] << 8 | rgb[:, :, 2]).ravel()
    image[::113] &= np.uint32(0x00ffffff)
    n = width * core_rows
    gw, gh = (width + 63) // 64, (full_height + 63) // 64
    evidence = np.empty(16 + 3 * gw * gh, np.float32)
    evidence[:16] = rng.uniform(0.4, 7.0, 16)
    evidence[16::3] = rng.uniform(0.5, 8.0, gw * gh)
    evidence[17::3] = rng.uniform(0.5, 9.0, gw * gh)
    evidence[18::3] = rng.uniform(0, 0.8, gw * gh)
    first_grid = max(0, min(gh - 1, int((128 + 4 + 0.5) / 64 - 0.5)))
    last_grid = min(gh, int((128 + 4 + core_rows - 1 + 0.5) / 64 - 0.5) + 2)
    u[13] = first_grid
    evidence = np.concatenate((evidence[:16], evidence[16 + 3 * gw * first_grid:16 + 3 * gw * last_grid]))
    policy = np.empty(2 * n, np.int32)
    policy[::2] = rng.choice([0, 90, 256], n)
    policy[1::2] = rng.choice([0, 90, 192, 256], n)
    maps = []
    mw, mh = width, full_height
    for k in range(3):
        mw, mh = (mw + 1) // 2, (mh + 1) // 2
        c = rng.integers(-24, 25, (mw * mh, 3), dtype=np.int32).astype(np.uint32) & 255
        values = (np.uint32(55 << 24) | c[:, 0] << 16 | c[:, 1] << 8 | c[:, 2]).astype(np.uint32)
        scale = 1 << (k + 1)
        first_map = int(max(0, min(mh - 1, (128 + 4 + .5) / scale - .5)))
        last_map = min(mh, int(max(0, min(mh - 1, (128 + 4 + core_rows - 1 + .5) / scale - .5))) + 2)
        u[15 + k] = first_map
        maps.append(values[first_map * mw:last_map * mw].copy())
    cn = ((width + 3) // 4) * ((core_rows + 3) // 4) if confidence else 1
    arrays = [image, np.zeros(n, np.uint32), evidence, policy, *maps, np.zeros(cn, np.int32)]
    return f"{width}x{full_height}-core{core_rows}-conf{confidence}", u, arrays, 0


def compare(reference, actual, name, fixture):
    result = []
    for label, a, b in (("ARGB", reference[0], actual[0]), ("confidence", reference[1], actual[1])):
        diffs = np.flatnonzero(a != b)
        result.append({"binding": label, "words": int(len(a)), "mismatches": int(len(diffs)),
                       "first_mismatch": int(diffs[0]) if len(diffs) else None})
        if len(diffs):
            raise AssertionError(f"{name} differs in {label}, {fixture}: {len(diffs)} words at {diffs[:8].tolist()}")
    return result


