#!/usr/bin/env python3
"""Build additive Maps Back/recents MPPs and audit their real APK output.

The native callback is generated by the provider. Tests inspect and execute its
small emitted instruction paths on the host; Android UI execution is separate.
"""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parent
VERSION, BASE_VERSION, BUNDLE_VERSION = '1.0.0', '1.0.362', '1.0.363'
BASE_SHA = 'd2a5637a670c17ac6a1ccbc346c0ad9c882737d1f661c2ad8de127720c7e56fd'
ORIGINAL_SHA = '7de0b555219eca65d40f751e64381e55cbd817a0c393fbd363a5d89feb17c063'
REPORTED_SHA = '238b2ed13f530e223f090625c30753d2c01bcb24cbfb9986059f23e14f290d71'
TOOLS = {
    'morphe.jar': 'b98ca01f1eaac8ea66a8c44a0555a08a9d200e8847dcc200723e5574b8d67c58',
    'morphe-2.2.jar': '855dd2d6fa5ed997a5884a44f8807c9b5bc95e69b5ebd58dfd7e8b897c86e2d7',
    'android.jar': '4566663c3876e022b4fa4ced8c8697c4ab1688267f090114fd92d027b32e619b',
    'r8.jar': 'badba8e0fd96dc9f41f53a0686f20fc08f1172a9816461fec13b6635b7c883fa',
}
PREFIX = 'app/hiro/mapsback/patches/'
MF = 'META-INF/MANIFEST.MF'
PATCH_NAME = '戻るで終了して履歴から削除'
EXISTING_NAMES = ['検索欄の下のカテゴリ行を非表示', '起動時に現在地を表示']
PACKAGES = ('org.ungoogled.android.apps.maps.microg', 'com.google.android.apps.maps')
APP_VERSION = '26.36.04.973607363'
SINGLE = 'Maps_Back_Exit_v1.0.0.mpp'
BUNDLE = 'Hiro_Morphe_Patches_v1.0.363.mpp'
QA_NAME = 'QA_Maps_Back_Exit_v1.0.0.json'


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def archive(path):
    with zipfile.ZipFile(path) as zipped:
        require(zipped.testzip() is None, 'Corrupt ZIP: ' + str(path))
        require(len(zipped.namelist()) == len(set(zipped.namelist())), 'Duplicate ZIP entry')
        return {name: zipped.read(name) for name in zipped.namelist() if not name.endswith('/')}


def headers(raw):
    rows = []
    for line in raw.replace(b'\r\n', b'\n').split(b'\n'):
        if line.startswith(b' '):
            require(rows, 'Invalid manifest continuation')
            rows[-1] += line[1:]
        elif line:
            rows.append(line)
    pairs = [row.decode().split(': ', 1) for row in rows]
    require(all(len(pair) == 2 for pair in pairs) and len(pairs) == len(dict(pairs)), 'Invalid manifest')
    return dict(pairs)


def manifest(fields):
    lines = []
    for key, value in fields.items():
        require(isinstance(value, str) and not any(c in value for c in '\r\n\0'), 'Invalid manifest field')
        raw, prefix = (key + ': ' + value).encode(), b''
        while len(prefix) + len(raw) > 72:
            cut = 72 - len(prefix)
            while raw[cut] & 192 == 128:
                cut -= 1
            lines.append(prefix + raw[:cut])
            raw, prefix = raw[cut:], b' '
        lines.append(prefix + raw)
    result = b'\r\n'.join(lines) + b'\r\n\r\n'
    require(headers(result) == fields, 'Manifest round trip differs')
    return result


def write_zip(path, entries):
    with zipfile.ZipFile(path, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as zipped:
        for name in sorted(entries, key=lambda n: (n != MF, n)):
            info = zipfile.ZipInfo(name, (2026, 11, 6, 0, 0, 0))
            info.external_attr = 0o100644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            zipped.writestr(info, entries[name], compress_type=zipfile.ZIP_DEFLATED, compresslevel=6)


def classes(folder):
    return {p.relative_to(folder).as_posix(): p.read_bytes() for p in sorted(folder.rglob('*.class'))}


def sources():
    return {str(p.relative_to(ROOT)): sha(p) for p in sorted(ROOT.rglob('*'))
            if p.is_file() and p.suffix in ('.py', '.java') and '__pycache__' not in p.parts}


def resource_hashes(path):
    with zipfile.ZipFile(path) as zipped:
        return {name: hashlib.sha256(zipped.read(name)).hexdigest() for name in zipped.namelist()
                if not name.endswith('/') and not re.fullmatch(r'classes(?:[0-9]+)?\.dex', name)
                and not (name.startswith('META-INF/') and
                         (name == MF or name.upper().endswith(('.SF', '.RSA', '.DSA', '.EC'))))}


def main():
    parser = argparse.ArgumentParser()
    for name in ('base', 'tools', 'work', 'dist', 'apk', 'reported-apk'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--timestamp', required=True, help='JST release timestamp, YYYY-MM-DDTHH:MM:SS')
    args = parser.parse_args()
    for name in ('base', 'tools', 'work', 'dist', 'apk', 'reported_apk'):
        setattr(args, name, getattr(args, name).resolve())
    require(re.fullmatch(r'2026-11-0[67]T\d\d:\d\d:\d\d', args.timestamp), 'Unexpected release timestamp')
    java, javac = args.tools / 'bin/java', args.tools / 'bin/javac'
    require(sha(args.base) == BASE_SHA, 'Baseline bundle differs')
    require(sha(args.apk) == ORIGINAL_SHA, 'Original supplied microG Maps APK differs')
    require(sha(args.reported_apk) == REPORTED_SHA, 'Reported microG Maps APK differs')
    for name, digest in TOOLS.items():
        require(sha(args.tools / name) == digest, 'Pinned tool mismatch: ' + name)
    require(not args.work.exists(), 'Fresh build directory required')
    require(not args.dist.exists() or not any(args.dist.iterdir()), 'Empty output directory required')
    args.work.mkdir(parents=True)
    args.dist.mkdir(parents=True, exist_ok=True)

    def run(command, log_name, timeout=900):
        print('RUN ' + log_name, flush=True)
        with (args.work / log_name).open('w') as output:
            result = subprocess.run(list(map(str, command)), stdout=output, stderr=subprocess.STDOUT, timeout=timeout)
        output = (args.work / log_name).read_text()
        require(result.returncode == 0, 'Failed ' + log_name + '\n' + output[-16000:])
        return output.strip()

    compiler = run([javac, '-version'], 'javac-version.txt')
    require(compiler == 'javac 17.0.20', 'Pinned javac17 wrapper required')
    runtime = run([java, '-version'], 'java-version.txt')
    source_hashes = sources()
    for name in ('patch', 'patch-dex', 'test', 'applications'):
        (args.work / name).mkdir()
    run([javac, '--release', '8', '-encoding', 'UTF-8', '-cp', args.tools / 'morphe.jar',
         '-d', args.work / 'patch', *sorted((ROOT / 'patch').glob('*.java'))], 'patch-javac.log')
    compile_cp = os.pathsep.join(map(str, (args.work / 'patch', args.tools / 'morphe.jar')))
    run([javac, '--release', '8', '-encoding', 'UTF-8', '-cp', compile_cp,
         '-d', args.work / 'test', *sorted((ROOT / 'test').glob('*.java'))], 'audit-javac.log')
    guards = []
    for sdk in ('morphe.jar', 'morphe-2.2.jar'):
        cp = os.pathsep.join(map(str, (args.work / 'test', args.work / 'patch', args.tools / sdk)))
        for label, apk in (('original-v285', args.apk), ('reported-v287', args.reported_apk)):
            result = run([java, '-Xmx3g', '-ea', '-cp', cp, 'MapsBackAudit', 'guards', apk], sdk + '.' + label + '.guards.txt')
            require('PASS' in result, 'Guard/native behavior audit incomplete')
            guards.append({'loader': sdk, 'input': label, 'result': result})
    write_zip(args.work / 'patch.jar', classes(args.work / 'patch'))
    run([java, '-cp', args.tools / 'r8.jar', 'com.android.tools.r8.D8', '--release', '--min-api', '26',
         '--lib', args.tools / 'android.jar', '--classpath', args.tools / 'morphe.jar',
         '--output', args.work / 'patch-dex', args.work / 'patch.jar'], 'patch-d8.log')
    require({p.name for p in (args.work / 'patch-dex').iterdir()} == {'classes.dex'}, 'Unexpected multidex')
    base = archive(args.base)
    require(headers(base[MF])['Version'] == BASE_VERSION, 'Baseline version differs')
    require(not any(name.startswith(PREFIX) for name in base), 'Back patch already present in baseline')
    (args.work / 'base.dex').write_bytes(base['classes.dex'])
    audit_cp = os.pathsep.join(map(str, (args.work / 'test', args.work / 'patch', args.tools / 'morphe-2.2.jar')))
    preservation = run([java, '-Xmx3g', '-ea', '-cp', audit_cp, 'MapsBackAudit', 'merge',
                        args.work / 'base.dex', args.work / 'patch-dex/classes.dex', args.work / 'merged.dex'], 'loader-preservation.txt')
    require('PASS' in preservation, 'Loader preservation check incomplete')
    additions = classes(args.work / 'patch')
    require(additions and all(name.startswith(PREFIX) for name in additions), 'Unexpected patch provider class scope')
    fields = headers(base[MF])
    fields.update(Version=BUNDLE_VERSION, Timestamp=args.timestamp,
                  Description='Maps Back exit removes its task from Recents. Register an enabled lowest-priority native callback before existing handlers, preserving nested navigation and predictive Back. Android UI execution unverified.')
    combined = {**base, **additions, 'classes.dex': (args.work / 'merged.dex').read_bytes(), MF: manifest(fields)}
    single = {**additions, 'classes.dex': (args.work / 'patch-dex/classes.dex').read_bytes(),
              MF: manifest({**fields, 'Name': 'Maps Back Exit', 'Version': VERSION})}
    preserved = {name: value for name, value in base.items() if name not in (MF, 'classes.dex')}
    require(all(combined[name] == value for name, value in preserved.items()), 'Existing bundle entry changed')
    for name, data in ((SINGLE, single), (BUNDLE, combined)):
        write_zip(args.dist / name, data)
        require(archive(args.dist / name) == data, 'Archive round trip differs')
    selection = []
    for name in (SINGLE, BUNDLE):
        for sdk in ('morphe.jar', 'morphe-2.2.jar'):
            for package in PACKAGES:
                listing = run([java, '-jar', args.tools / sdk, 'list-patches', '--patches', args.dist / name,
                               '-f', package, '-p', '-v'], name + '.' + sdk + '.' + package + '.listing.txt')
                require(listing.count('Name: ' + PATCH_NAME + '\n') == 1, 'New patch not discoverable exactly once')
                if name == BUNDLE:
                    for existing in EXISTING_NAMES:
                        require(listing.count('Name: ' + existing + '\n') == 1, 'Existing Maps option lost: ' + existing)
                selection.append({'artifact': name, 'loader': sdk, 'package': package, 'matches': 1})

    applications = []

    def apply(mpp, names, label, source_apk):
        directory = args.work / 'applications' / label
        directory.mkdir()
        apk, report = directory / 'patched.apk', directory / 'morphe.json'
        command = [java, '-Xmx4g', '-jar', args.tools / 'morphe-2.2.jar', 'patch', source_apk,
                   '-p', mpp, '--exclusive', '--unsigned', '--bytecode-mode', 'STRIP_FAST',
                   '-o', apk, '-t', directory / 'tmp', '-r', report]
        for name in names:
            command += ['-e', name]
        run(command, label + '.apply.log')
        result = json.loads(report.read_text())
        applied = [item['name'] if isinstance(item, dict) else item for item in result.get('appliedPatches', [])]
        steps = result.get('stepResults', result.get('patchingSteps', []))
        require(apk.exists() and result.get('success', True) is True and not result.get('failedPatches')
                and set(applied) == set(names) and len(applied) == len(names)
                and result.get('packageName') == PACKAGES[0] and result.get('packageVersion') == APP_VERSION
                and steps and all(step.get('success') is True for step in steps), 'Actual APK application failed')
        resources = resource_hashes(source_apk)
        require(resource_hashes(apk) == resources, 'APK manifest/resources/native libraries changed')
        return apk, len(resources)

    for artifact, label, input_apk in ((SINGLE, 'standalone-original', args.apk),
                                      (BUNDLE, 'integrated-reported', args.reported_apk)):
        apk, resource_count = apply(args.dist / artifact, [PATCH_NAME], label, input_apk)
        audit = run([java, '-Xmx4g', '-ea', '-cp', audit_cp, 'MapsBackAudit', 'audit', input_apk, apk], label + '.audit.txt')
        require('PASS' in audit, 'Application bytecode audit incomplete')
        applications.append({'artifact': artifact, 'label': label, 'input_sha256': sha(input_apk),
                             'result': 'PASS', 'audit': audit, 'preserved_resource_entries': resource_count})
    previous, previous_resources = apply(args.base, EXISTING_NAMES, 'existing-maps-baseline', args.apk)
    coapplied, coexistence_resources = apply(args.dist / BUNDLE, EXISTING_NAMES + [PATCH_NAME], 'all-three-maps', args.apk)
    coexistence = run([java, '-Xmx4g', '-ea', '-cp', audit_cp, 'MapsBackAudit', 'audit', previous, coapplied],
                      'all-three-maps.audit.txt')
    require('PASS' in coexistence and previous_resources == coexistence_resources,
            'Existing startup/category patch coexistence audit incomplete')
    require(sources() == source_hashes, 'Sources changed during build')
    qa = {'schema': 'maps-back100-qa-v1', 'patch_version': VERSION, 'bundle_version': BUNDLE_VERSION,
          'patch_name': PATCH_NAME, 'release_timestamp': args.timestamp, 'release_timezone': 'Asia/Tokyo',
          'baseline_version': BASE_VERSION, 'baseline_sha256': BASE_SHA,
          'physical_android_tested': False, 'android_emulator_tested': False, 'runtime_android_tested': False,
          'runtime_limitation': 'No usable Android emulator/ADB or connected device is available. APK application, emitted instruction host tests, native dispatcher structure and preservation were checked; Android UI behavior is unverified.',
          'compiler': compiler, 'java_runtime': runtime, 'toolchain_sha256': TOOLS,
          'apk_bytecode_mode': 'STRIP_FAST', 'apk_patcher_version': '2.2.0',
          'source_sha256': source_hashes, 'selection_results': selection,
          'guard_and_emitted_instruction_tests': guards, 'loader_preservation': preservation,
          'preserved_bundle_entries': len(preserved), 'apk_applications': applications,
          'three_patch_coexistence': {'patches': EXISTING_NAMES + [PATCH_NAME], 'result': 'PASS', 'audit': coexistence,
                                     'preserved_resource_entries': coexistence_resources},
          'input_sha256': {'original_v285': ORIGINAL_SHA, 'reported_v287': REPORTED_SHA},
          'artifacts': {name: {'bytes': (args.dist / name).stat().st_size, 'sha256': sha(args.dist / name)}
                        for name in (SINGLE, BUNDLE)}}
    (args.dist / QA_NAME).write_text(json.dumps(qa, ensure_ascii=False, indent=2) + '\n')
    print('PASS BUILD ' + json.dumps(qa['artifacts']), flush=True)


if __name__ == '__main__':
    main()
